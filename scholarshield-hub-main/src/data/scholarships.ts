export function computeApplicationStatus(s: Pick<Scholarship, "is_active" | "opening_date" | "closing_date">): ApplicationStatus {
  if (!s.is_active) return "Closed";
  const today = new Date().toISOString().slice(0, 10);
  if (s.closing_date && s.closing_date < today) return "Closed";
  if (s.opening_date && s.opening_date > today) return "Upcoming";
  if (s.closing_date && s.closing_date >= today) return "Open";
  if (s.opening_date && s.opening_date <= today && !s.closing_date) return "Open";
  return "Not Announced";
}

export function computeVerificationStatus(s: Pick<Scholarship, "unverified_fields">): VerificationStatus {
  return s.unverified_fields && s.unverified_fields.length === 0 ? "Verified" : "Needs Verification";
}

